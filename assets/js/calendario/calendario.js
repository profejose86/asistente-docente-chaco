function adcCalendarOpen(){
 const year=$('adcCalYear');
 if(year.childElementCount)return;
 for(let month=0;month<12;month++){
  const start=Date.UTC(adcSchoolYear,month,1), end=Date.UTC(adcSchoolYear,month+1,1);
  const card=document.createElement('article'), title=document.createElement('h3'), grid=document.createElement('div');
  const monthButton=document.createElement('button');
  monthButton.type='button';
  monthButton.className='adc-cal-month-name';
  monthButton.textContent=adcCalMonths.format(start);
  monthButton.onclick=()=>adcCalShowMonth(monthButton,grid,start,end);
  title.append(monthButton);
  grid.className='adc-cal-days';
  for(const weekday of ['Lu','Ma','Mi','Ju','Vi','Sá','Do']){
   const label=document.createElement('span');label.className='adc-cal-weekday';label.textContent=weekday;grid.append(label);
  }
  for(let i=0;i<(new Date(start).getUTCDay()+6)%7;i++)grid.append(document.createElement('span'));
  for(let time=start;time<end;time+=adcCalDay){
   const date=adcCalISO(time), button=document.createElement('button');
   button.type='button';
   button.dataset.date=date;
   button.textContent=new Date(time).getUTCDate();
   const categories=[...new Set(adcCalFor(date).map(event=>event[3]))];
   const dots=document.createElement('span');
   dots.className='adc-cal-dots';
   dots.setAttribute('aria-hidden','true');
   for(const category of categories){
    const dot=document.createElement('i');
    dot.className='adc-cal-dot';
    dot.dataset.cat=category;
    dots.append(dot);
   }
   button.append(dots);
   button.setAttribute('aria-label',adcCalFullDate.format(time)+(categories.length?', '+categories.map(key=>adcCalCategories[key]).join(', '):''));
   button.onclick=()=>adcCalendarSelect(date);
   grid.append(button);
  }
  card.append(title,grid);
  year.append(card);
 }
 adcCalInitDivider();
 adcCalPaintPersonal();
 adcCalendarSelect(adcCalSelected);
}
