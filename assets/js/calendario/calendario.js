function adcCalInitDivider(){
 const divider=document.querySelector('#adcCalendar .adc-cal-divider'), layout=divider.parentElement;
 let value=48;
 function resize(percent){
  value=Math.round(Math.max(35,Math.min(68,percent)));
  layout.style.setProperty('--calendar-width',value+'%');
  divider.setAttribute('aria-valuenow',String(value));
 }
 divider.onpointerdown=event=>divider.setPointerCapture(event.pointerId);
 divider.onpointermove=event=>{
  if(!divider.hasPointerCapture(event.pointerId))return;
  const bounds=layout.getBoundingClientRect();
  resize(100*(event.clientX-bounds.left-10)/bounds.width);
 };
 divider.onkeydown=event=>{
  if(event.key!=='ArrowLeft'&&event.key!=='ArrowRight')return;
  event.preventDefault();
  resize(value+(event.key==='ArrowRight'?2:-2));
 };
}

